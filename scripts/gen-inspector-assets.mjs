// Embeds the inspector's static UI into src/inspector/assets.ts so the compiled package serves it without reading the
// filesystem at runtime (the package allowlist only ships dist/**/*.js). CI re-runs this and fails on any diff.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ui = path.join(root, 'src', 'inspector', 'ui');
const out = path.join(root, 'src', 'inspector', 'assets.ts');

const FILES = [
  ['/', 'index.html', 'text/html; charset=utf-8'],
  ['/app.js', 'app.js', 'text/javascript; charset=utf-8'],
  ['/app.css', 'app.css', 'text/css; charset=utf-8'],
];

const entries = FILES.map(([route, file, type]) => {
  const body = fs.readFileSync(path.join(ui, file), 'utf8').replace(/\r\n/g, '\n');
  return `  ${JSON.stringify(route)}: { type: ${JSON.stringify(type)}, body: ${JSON.stringify(body)} },`;
});

const text = `// GENERATED by scripts/gen-inspector-assets.mjs from src/inspector/ui/*. Do not edit; run \`npm run gen:assets\`.
export const ASSETS: Record<'/' | '/app.js' | '/app.css', { type: string; body: string }> = {
${entries.join('\n')}
};
`;
fs.writeFileSync(out, text);
