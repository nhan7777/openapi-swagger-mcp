// Regenerates THIRD_PARTY_NOTICES.md from the runtime (non-dev) dependency tree in package-lock.json.
// Usage: npm ci && node scripts/gen-notices.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const entries = Object.entries(lock.packages)
  .filter(([p, m]) => p && !m.dev && !m.devOptional && !m.optional)
  .map(([p, m]) => ({ dir: path.join(root, p), name: p.replace(/^.*node_modules\//, ''), version: m.version }))
  .sort((a, b) => (a.name + a.version < b.name + b.version ? -1 : 1));

const out = [
  '# Third-party notices',
  '',
  'openapi-swagger-mcp is MIT licensed. It depends at runtime on the packages below, each under its own license.',
  'This file is generated by `node scripts/gen-notices.mjs` from package-lock.json and the installed packages.',
  '',
];
const missing = [];
for (const e of entries) {
  const pkg = JSON.parse(fs.readFileSync(path.join(e.dir, 'package.json'), 'utf8'));
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN');
  const files = fs.readdirSync(e.dir).filter((f) => /^(licen[sc]e|copying|notice)(\.|$)/i.test(f));
  out.push(`## ${e.name}@${e.version}`, '', `License: ${license}`, '');
  if (files.length === 0) {
    missing.push(e.name);
    out.push('(no license file shipped in the package; license declared in package.json)', '');
    continue;
  }
  for (const f of files) {
    out.push('```text', fs.readFileSync(path.join(e.dir, f), 'utf8').trim(), '```', '');
  }
}
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'));
console.log(`wrote ${entries.length} packages` + (missing.length ? `; no license file: ${missing.join(', ')}` : ''));
