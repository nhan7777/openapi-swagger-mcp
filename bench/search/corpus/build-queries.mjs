const rows = [];
for (const [category, list] of Object.entries(C)) {
  if (list.length !== 15) throw new Error(`${category}: expected 15 queries, got ${list.length}`);
  list.forEach(([lang, query, rel, opts = {}], i) => {
    const relevant = rel.map((r) => {
      const grade = r.startsWith('~') ? 1 : 2;
      const id = r.replace(/^~/, '');
      const key = keyOf.get(id);
      if (!key) throw new Error(`unknown operation label ${id}`);
      return { service: id.split('/')[0], operation: key, grade };
    });
    rows.push({
      id: `${category}-${String(i + 1).padStart(2, '0')}`,
      category,
      lang,
      query,
      ...(opts.service ? { service: opts.service } : {}),
      ...(opts.fields ? { fields: opts.fields } : {}),
      ...(category === 'paraphrase_alias' ? { requiresAlias: true } : {}),
      relevant,
      split: i % 2 === 0 ? 'dev' : 'test',
    });
  });
}
fs.writeFileSync(path.join(here, '..', 'queries.jsonl'), rows.map((r) => JSON.stringify(r)).join('\n') + '\n');
console.log(`wrote ${rows.length} queries`);
